-- Ticker import staging table.
-- Populated from the Excel import list; admin uses this to review and import
-- tickers into the main ticker tables (market_segments, sectors, mega_caps, other_stocks).
-- The scan action validates each ticker against the configured provider's symbol
-- catalog and marks existing system tickers before admin decides what to import.

create table if not exists public.ticker_import_candidates (
  id uuid primary key default gen_random_uuid(),
  ticker text not null unique,

  -- Provider validation fields (populated by the Scan action)
  provider_name text,                     -- company/fund name from the provider catalog
  provider_type text,                     -- 'ETP', 'Common Stock', etc.
  provider_mic  text,                     -- exchange MIC: 'XNYS', 'XNAS', etc.
  provider_status text not null default 'pending'
    check (provider_status in ('pending', 'found', 'not_found', 'error')),

  -- System cross-reference (populated by the Scan action)
  is_in_system   boolean not null default false,
  existing_table text,                    -- which table it already lives in

  -- Import decision (set by admin via the import UI)
  import_status text not null default 'pending'
    check (import_status in ('pending', 'imported', 'skipped')),
  import_target_table text
    check (import_target_table in ('market_segments', 'sectors', 'mega_caps', 'other_stocks')),

  -- Audit
  notes        text,
  scanned_at   timestamptz,
  scanned_by   text,
  imported_at  timestamptz,
  imported_by  text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- Indexes for common filter patterns used by the admin UI
create index if not exists tic_provider_status  on public.ticker_import_candidates (provider_status);
create index if not exists tic_import_status    on public.ticker_import_candidates (import_status);
create index if not exists tic_is_in_system     on public.ticker_import_candidates (is_in_system);

-- Aggregate stats function (avoids Supabase client 1000-row cap)
create or replace function public.get_ticker_import_stats()
returns jsonb language sql stable as $$
  select jsonb_build_object(
    'total',           count(*),
    'pending_scan',    count(*) filter (where provider_status = 'pending'),
    'found',           count(*) filter (where provider_status = 'found'),
    'not_found',       count(*) filter (where provider_status = 'not_found'),
    'in_system',       count(*) filter (where is_in_system = true),
    'imported',        count(*) filter (where import_status = 'imported'),
    'skipped',         count(*) filter (where import_status = 'skipped'),
    'ready_to_import', count(*) filter (where provider_status = 'found' and is_in_system = false and import_status = 'pending')
  )
  from public.ticker_import_candidates;
$$;

